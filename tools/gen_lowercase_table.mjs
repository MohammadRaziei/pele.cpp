// Writes src/lowercase_data.inc: the ranges of code points that String.prototype.toLowerCase changes.
// `s !== s.toLowerCase()` holds exactly when `s` has one of them, whatever surrounds it (a capital
// sigma becomes one of two letters by context, but it always changes).   node tools/gen_lowercase_table.mjs
import fs from 'fs';
const ranges = [];
let start = -1;
for (let cp = 0; cp <= 0x10ffff + 1; cp++) {
  const changes = cp <= 0x10ffff && !(cp >= 0xd800 && cp <= 0xdfff) && String.fromCodePoint(cp).toLowerCase() !== String.fromCodePoint(cp);
  if (changes && start < 0) start = cp;
  if (!changes && start >= 0) { ranges.push([start, cp - 1]); start = -1; }
}
const rows = [];
for (let i = 0; i < ranges.length; i += 6) rows.push('    ' + ranges.slice(i, i + 6).map(([a, b]) => `{0x${a.toString(16)}, 0x${b.toString(16)}}`).join(', ') + ',');
fs.writeFileSync('src/lowercase_data.inc', `// Generated by tools/gen_lowercase_table.mjs with Node ${process.version} (Unicode ${process.versions.unicode}). Do not edit.\n${rows.join('\n')}\n`);
console.log(ranges.length, 'ranges; unicode', process.versions.unicode);
